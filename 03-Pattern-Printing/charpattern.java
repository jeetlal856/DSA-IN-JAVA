public class charpattern {
    public static void main(String[] args) {

        int n=4;
        int k=65;
        for(int i=1;i<=n;i++){
            for(int j=1;j<=i;j++){
              
                  char ch=(char)(k);
                   System.out.print(ch);
                    k=k+1;
               
              

            }
            System.out.println();
        }
        
    }
    
}
